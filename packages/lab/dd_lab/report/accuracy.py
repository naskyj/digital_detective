"""The classifier's measured error rate, as a statement for the report.

A report that ranks evidence without saying how much it is expected to have
MISSED invites the reader to treat the list as complete. The measurement
exists — it is in docs/PAPER.md §7.6 — but until this module it was never
carried into the artifact an examiner actually reads. docs/CLAIMS_AUDIT.md
records that gap as #10, against the claim "disclosed, known error rate".

Why these numbers live in code rather than being recomputed: they come from a
hand-annotated corpus of 557,834 artifacts that is not shipped with the tool
and cannot be reconstructed at report time. They are therefore a recorded
measurement with its provenance attached, not a live computation, and the
report says so. A deployment whose evidence differs materially from the
measured corpus should expect different rates — which is also stated.

Keep this in step with docs/PAPER.md: `scripts/paper_metrics.py` regenerates
the figures, and the version string below should change whenever they do.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class AccuracyStatement:
    """A measured operating point, with enough provenance to be checked."""

    classifier_version: str
    corpus_artifacts: int
    corpus_positives: int
    recall: float
    precision: float
    known_misses: int
    #: Share of the corpus the measurement was taken on that was carved memory
    #: rather than structured application storage — the single biggest driver
    #: of the precision figure (paper §7.6).
    memory_share: float
    in_sample: bool

    @property
    def prevalence(self) -> float:
        return self.corpus_positives / self.corpus_artifacts

    def sentences(self) -> list[str]:
        """Plain statements for the report. Deliberately prose rather than a
        metric table: the audience is an examiner deciding how much to trust a
        ranked list, not a reader comparing classifiers."""
        pct = f"{100 * self.recall:.1f}%"
        return [
            f"On a hand-annotated corpus of {self.corpus_artifacts:,} artifacts "
            f"({self.corpus_positives:,} of them relevant, {100 * self.prevalence:.2f}%), "
            f"this classifier version found {pct} of the relevant material and "
            f"missed {self.known_misses}.",
            f"Of what it flags, roughly {100 * self.precision:.0f}% was judged relevant by "
            "the annotator; the rest is material an examiner would discard on sight. "
            "That ratio is dominated by carved memory strings, which were "
            f"{100 * self.memory_share:.0f}% of the measured corpus and carry almost all "
            "of the error — on structured application storage (cookies, IndexedDB, "
            "preferences) the measured false-positive count was zero.",
            "This is a recorded measurement from a reference corpus, not a "
            "measurement of the present case. Evidence materially unlike that "
            "corpus should be expected to differ."
            + (" The measurement is also in-sample for the learned model, so it is "
               "an optimistic bound rather than an unbiased estimate."
               if self.in_sample else ""),
            "No automated triage is exhaustive. The absence of an artifact from "
            "this report is not evidence that it does not exist in the acquired "
            "data; use the review queue to examine what was not flagged.",
        ]


#: The deployed measurement. Regenerated by scripts/paper_metrics.py over the
#: annotated corpus; see docs/PAPER.md §7.6 for the full breakdown and §10 for
#: the threats that qualify it.
DEPLOYED = AccuracyStatement(
    classifier_version="ensemble-0.3.0",
    corpus_artifacts=557_834,
    corpus_positives=1_283,
    recall=0.9579,
    precision=0.4273,
    known_misses=54,
    memory_share=0.982,
    in_sample=True,
)


def statement_for(classifier_version: str) -> AccuracyStatement | None:
    """The measurement matching a report's classifier version, or None.

    Returning None rather than the nearest match is deliberate: a figure
    measured on a different classifier is worse than no figure, because the
    reader cannot tell it does not apply.
    """
    return DEPLOYED if classifier_version == DEPLOYED.classifier_version else None
